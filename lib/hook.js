// lib/hook.js — 纯函数：章末钩子检测（共享逻辑，消除 audit/diagnose/polish 三处重复）。
// 返回 null（无钩子）或 kind 字符串。

const SUSPENSE_WORDS = /(突然|忽然|竟然|却不知|就在这时|下一瞬|还没等|紧接着|可就在|来不及|转眼间)/;
// 倒计时式宣告与打断式收尾——真机导入书两处教科书级 cliffhanger，旧四模式全检不出。
// 模式取窄：只认明确的倒计时/打断措辞，宽松化会制造假阳性驱动无谓改稿。
const CLOCK_RE = /(最多(还)?能?(再)?活|最多(还)?剩|只剩(下)?最后|大限(将至|只剩)|数到第[一二三四五六七八九十百两0-9]{1,5}(下|声|次|个))/;
const INTERRUPT_RE = /(话音未落|话没说完|门被敲响|敲门声(突然)?响(了|起)?|骤然(响起|炸响|传来)|戛然而止)/;
// 0.20.0（真机《样书C》6/6 章漏检）：**预告式收尾**——陈述句把一个具体事件明确
// 指向未来（倒计时宣告/等待中/未落定），是账簿流、规则流网文的标准断章形态：
// 「明日，第三位客人的日子，就到了。」「他的账，簿子也在等。」「是簿子还没落笔。」
// 模式仍取窄：必须有「明日/明早/天亮前」的时间锚，或「在等/还没落笔/还没到…日子」
// 的未落定措辞收尾——避免把普通陈述句误判成钩子、驱动无谓改稿。
const FORESHADOW_RE = /(^|[。\n”])\s*(明日|明早|天亮(之前|以前|前))|(也|正|还)在等[。””"]{0,2}\s*$|(还没(落笔|揭晓|到来|开始)[。””"]{0,2}\s*$)|(还没到.{0,8}(日子|时候)[。””"]{0,2}\s*$)|((先|就|快)到了[。””"]{0,2}\s*$)/;
// 1.0.1（真机 20 章监控 9 例漏检定型）：四类扩展，**全部取窄**——宁可维持漏检现状
// （最多驱动一次人工确认），不制造假阳性驱动无谓改稿（0.19.0 纯感叹收尾的教训同源）。
// ① 拟声收尾：同一拟声字连响 ≥2 次收尾（「笃。笃。」「咚。咚。咚。」）——叩门/更鼓/
//    马蹄 cliffhanger（真机第 7 章「笃。笃。笃。」漏检）。单字不认（「当」的一声太常见）。
const ONOMATOPOEIA_RE = /([笃咚砰嗒哒当铛吱呀])\s*[。！.]\s*\1(?:\s*[。！.]\s*\1)?[。！]?\s*$/;
// ② 省略型：指代主语+「没+言说动词（可带 ≤6 字宾语）」收尾（真机第 11 章「他没说。」、
//    第 16 章「谁也没提昨夜的事。」）——话到嘴边的悬置。
const ELISION_RE = /(他|她|它|谁|两人|二人|他们|她们|爷儿俩)([^。！？]{0,8})?没(说|提|问|答|吭声|开口|接话|再说话)[^。！？]{0,6}[。！]?\s*$/;
// ③ 宣告型：独立短句「来了。」「到了。」「找上门了。」收尾（真机第 13 章「来了。」）。
//    主语排除食物/天气等日常宾语（「菜来了。」「雪到了。」不是钩子）。
const ANNOUNCE_RE = /(?:^|[。\n！？”，])\s*(?!(?:菜|饭|汤|水|茶|酒|信|货|钱|风|雨|雪|天|灯)[来了到])[^。，\n]{0,4}?(来了|到了|找上门了)[。！]?\s*$/;
// ④ 在场型：「他就在。」「它还在。」（真机第 15 章「簿子还在写。他就在。」）——
//    悬置的在场宣告。比喻收尾（「像一扇门轻轻落下了闩」）仍不在检测范围：正则
//    分不出比喻与平叙，硬抓会误伤，留给人工/模型自查。
const PRESENCE_RE = /(他|她|它|谁)([^。，]{0,4})?(就在|还在)[。！]?\s*$/;
// ⑤ 预约时点（W4 取窄用）：必须是一个**可指认的时刻/时长**——数字或中文数字紧贴时间
//   单位（十点 / 三分钟 / 五日），或明晚/午夜这类时间锚词。单字「时」「点」不算：
//   「他走到门口时停下了」里也有「时」，放行等于把普通叙事全判成钩子。
const APPOINT_NUM = '(?:[0-9]{1,2}|[一二三四五六七八九十]{1,3}|半|两)';
const APPOINT_TIME_RE = new RegExp(
    `${APPOINT_NUM}\\s*(?:点|时|刻|分|分钟|小时|秒钟|天|日|号|周|月|年)`
    + '|零点|午夜|正午|凌晨|傍晚|深夜|中午|明晚|今晚|明早|明天|后天|次日|月底|周末|下周|下月',
);

/**
 * 剥掉 markdown 强调标记（**粗体** / __下划线__ / *斜体* / _斜体_）。
 * 两个消费者必须共用这一个口径，否则数字与判定会互相矛盾：
 *   · detectHookKind —— 钩子存在性不该被排版标记绑架（真机「**三个！**」的 `**` 挡住结尾正则）；
 *   · audit 字数 —— `**` 是排版不是正文，真机一章 188 个 `*` 被算成 188 字，
 *     门禁报「正文 1905 字」而读者实际只看到 1717 字（差 95 是假的，真实差 283）。
 * 纯函数。
 */
export function stripEmphasis(text) {
    return String(text ?? '').replace(/[*_]+/g, '');
}

/**
 * 章末钩子检测（看最后 160 字）。
 * 先剥 markdown 强调标记：真机「**三个！**」的 `**` 挡住结尾正则，
 * 检测器对明明存在的钩子报「未检出」，模型随即整章重写提修复提案（真机连犯 16 例「同型吞检」，
 * 每例一轮 propose+人工应用）——钩子存在性判定不该被排版标记绑架。
 * 0.19.0：**纯感叹收尾不再算钩子**。《某连载本》105 章审校实证：exclaim 是五类里
 * 成本最低的一档——模型收尾打个「它，还醒着！」既满足 hook 检测、又满足 content-gate 的
 * 「开新钩」判定（欠账未还禁开新钩也被一个叹号绕过），100+ 章「一句宣言+叹号」同构率
 * 近乎 100%，是可检测的生成痕迹。语义钩（问句/悬念/省略/倒计时/打断）保留。
 * @returns null | 'question' | 'ellipsis' | 'suspense' | 'countdown' | 'interrupt'
 */
export function detectHookKind(text) {
    const tail = stripEmphasis(text).trim().slice(-160);
    if (tail === '') return null;
    if (/[「"][^」”]*[？?][」”]?\s*$/.test(tail) || /[？?]\s*[」”]?\s*$/.test(tail)) return 'question';
    // 修辞性问句（句号收尾）：选择问「应，还是不应。」+ 特指问「谁动过我哥的账。」
    // ——问式词紧跟逗号；特指问「谁」要求句中「谁」仅出现一次（双「谁」是「谁先来谁先拿」
    // 这类规则陈述句，不是问句）。白名单问式防「他最终还是走了。」这类陈述句误判；
    // 真机《样书B》第 2 章漏检样例（E3）、第 9 章闭环验证抓出特指问漏检（E3b）。
    if (/，(?:还是(?:不|要|能|会|行|去|来)|(?:该|应|又)?由?谁|什么|怎么|哪)[\u4e00-\u9fff]{0,6}。\s*$/.test(tail)) {
        const whoCount = (tail.match(/谁/g) ?? []).length;
        if (whoCount < 2) return 'question';
    }
    if (/(……|—{2,})\s*$/.test(tail)) return 'ellipsis';
    if (SUSPENSE_WORDS.test(tail)) return 'suspense';
    if (CLOCK_RE.test(tail)) return 'countdown';
    if (INTERRUPT_RE.test(tail)) return 'interrupt';
    if (FORESHADOW_RE.test(tail)) return 'foreshadow';
    // 1.0.1 四类扩展（见顶部注释；顺序无依赖，先到先得）
    // W4（真机《深夜订单》监控）：预约/推送式收尾——「【配送完成】明晚十点整。」
    // 「配送时间：明晚十点整。」把一个具体约定钉在章末。取窄：必须由【】推送标签
    // 或「配送/送达/取餐/出发+冒号」显式开场，普通时间陈述句（「今晚十点。」）不受影响。
    // 1.0.2 取窄：标签/冒号开场后必须**真的钉了一个约定时点**才算预约式收尾。
    // 首版只要求「标签后跟 ≤20 个非句号字符」，于是「【系统】他点了点头。」「【全书完】」
    // 这类普通叙事也判 announce —— 假阳性比漏检贵：把「无钩」报成「有钩」，等于放行
    // 一次真正的断章（0.19.0 纯感叹收尾的同源教训）。
    const appt = tail.match(/【[^】]{2,20}】([^。\n]{0,24})\s*[。！]?\s*$/)
        ?? tail.match(/(?:配送|送达|取餐|出发)[^\s：:]{0,4}[:：]\s*([^。\n]{0,24})\s*[。！]?\s*$/);
    if (appt && APPOINT_TIME_RE.test(appt[1])) return 'announce';
    if (ONOMATOPOEIA_RE.test(tail)) return 'onomatopoeia';
    if (ELISION_RE.test(tail)) return 'elision';
    if (ANNOUNCE_RE.test(tail)) return 'announce';
    if (PRESENCE_RE.test(tail)) return 'presence';
    // 纯感叹收尾不返回任何 kind——它是断章公式（noai.formula 维）的检测对象，不是钩子。
    return null;
}
